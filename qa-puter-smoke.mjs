import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
const root = path.dirname(new URL(import.meta.url).pathname);
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');
const auth = read('appAdmin/server/routes/auth.js');
const gen = read('appAdmin/server/routes/generate.js');
const worker = read('worker/index.js');
const bridge = read('appAdmin/server/public/puter-bridge.html');
const nativeAuth = read('app/src/context/AuthContext.js');
const nativePuter = read('app/src/utils/puter.js');
const appJson = JSON.parse(read('app/app.json'));
assert.match(auth, /router\.post\('\/puter\/issue'/);
assert.match(auth, /router\.post\('\/puter\/exchange'/);
assert.match(auth, /findOneAndDelete\(\{ codeHash, expiresAt/);
assert.match(auth, /timingSafeEqual/);
assert.match(gen, /router\.post\('\/puter-reference-upload'/);
assert.match(gen, /router\.post\('\/puter-record'/);
assert.match(worker, /user\.puter\.getUser\(\)/);
assert.match(worker, /user\.puter\.ai\.txt2img/);
assert.match(worker, /user\.puter\.fs\.getReadURL/);
assert.match(bridge, /puter\.auth\.signIn\(\)/);
assert.match(bridge, /puter\.workers\.exec/);
assert.match(nativeAuth, /SecureStore\.setItemAsync\('token'/);
assert.match(nativePuter, /openAuthSessionAsync/);
assert.equal(appJson.expo.scheme, 'somyalaya');
assert.equal(appJson.expo.android.package, 'com.promptfoundry.app');
assert.ok(!fs.existsSync(path.join(root, 'appAdmin/server/.env')), 'server .env must not be included');
console.log('PASS: Puter integration static smoke checks');
console.log('PASS: one-time auth exchange, SecureStore, Worker user-context billing, Puter output storage, Android deep-link scheme');
