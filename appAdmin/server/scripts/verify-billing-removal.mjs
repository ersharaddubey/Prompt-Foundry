import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
const root = path.resolve(process.cwd());
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');
const generate = read('routes/generate.js');
assert.match(generate, /aihorde\.net\/api\/v2/, 'AI Horde must be the active image provider');
assert.match(generate, /hourlyLimit: 3/, 'Hourly free quota must remain 3');
assert.match(generate, /dailyLimit: 10/, 'Daily free quota must remain 10');
assert.match(generate, /uploadToImageKit/, 'Generated images must be saved to ImageKit');
const appRoot = path.resolve(root, '../../app');
assert.match(fs.readFileSync(path.join(appRoot, 'src/screens/PricingScreen.js'), 'utf8'), /Puter/, 'AI Billing screen must remain available');
assert.doesNotMatch(fs.readFileSync(path.join(appRoot, 'src/screens/GenerateScreen.js'), 'utf8'), /Puter/i, 'Generation screen must not show old provider branding');
console.log('PASS: AI Horde provider, rolling free quota, ImageKit gallery, and separate AI Billing screen verified.');
